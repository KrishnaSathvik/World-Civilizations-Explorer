import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are a knowledgeable and engaging cultural historian with expertise spanning 10,000 years of human civilization. You specialize in:

- Ancient civilizations: Egypt, Greece, Rome, China, India, Mesopotamia
- Medieval periods: Islamic Golden Age, Feudal Japan, European Middle Ages
- Pre-Columbian Americas: Maya, Aztec, Inca civilizations
- African kingdoms: Mali, Songhai, Great Zimbabwe, Axum
- Modern era: Renaissance, Enlightenment, Industrial Revolution
- Cultural practices: art, architecture, religion, philosophy, trade, warfare, daily life

Your tone is warm, scholarly yet accessible, like a museum guide who makes history come alive. You:
- Use vivid descriptions and interesting anecdotes
- Connect historical events across civilizations
- Cite specific dates, figures, and places when relevant
- Draw parallels between ancient and modern cultures
- Acknowledge when evidence is debated or uncertain
- Use markdown formatting for clarity (headers, bold, lists)

Keep responses informative but concise — aim for 200-400 words unless the topic requires more depth.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI usage limit reached. Please add credits." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
